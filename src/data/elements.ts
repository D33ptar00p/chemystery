/**
 * Element data for CheMystery — all 118 elements.
 *
 * PROVENANCE
 * ----------
 * - Atomic masses: IUPAC 2021 standard atomic weights; for elements with no
 *   stable isotope, the mass number of the longest-lived isotope.
 * - van der Waals radii: Bondi (1964) where he gives one, otherwise Alvarez
 *   (2013), which covers almost the whole table. Superheavy elements (Z >= 100)
 *   have no measured radius at all; they carry a uniform 2.46 A placeholder so
 *   they render at a plausible size. Those are NOT measurements.
 * - Covalent radii: Cordero et al. (2008) single-bond radii.
 * - Electronegativity: Pauling scale; null where none is defined.
 *
 * COLOURS
 * -------
 * The product rule is "real-world appearance wherever possible", so every
 * element records WHY it has its colour via `colourBasis`, and the UI shows
 * that to the user rather than implying a colourless gas is coloured:
 *   bulk       - genuinely what the element looks like.
 *   liquid     - colourless as a gas, this is its real liquid colour (O2).
 *   discharge  - colourless in bulk, this is its real discharge-tube glow.
 *   flame      - the standard flame-test colour.
 *   predicted  - never observed in bulk; a relativistic-chemistry prediction.
 *   unknown    - never observed and not meaningfully predicted; neutral grey.
 *
 * Colours are tuned to read against the app's near-black canvas, so genuinely
 * black elements are lightened slightly; their `appearance` text says so.
 *
 * CAVEAT: this table was authored from standard reference values rather than
 * verified source-by-source. The radii for the heavy transition metals and
 * everything above Z = 99 are the least certain entries. Worth a pass by the
 * chemistry-specialist agent before relying on any single number.
 */

export type ColourBasis = 'bulk' | 'liquid' | 'discharge' | 'flame' | 'predicted' | 'unknown'
export type Material = 'metallic' | 'matte' | 'gas' | 'glassy'
export type ElementPhase = 'solid' | 'liquid' | 'gas'
export type Category =
  | 'alkali-metal'
  | 'alkaline-earth'
  | 'transition-metal'
  | 'post-transition-metal'
  | 'metalloid'
  | 'reactive-nonmetal'
  | 'halogen'
  | 'noble-gas'
  | 'lanthanide'
  | 'actinide'
  | 'unknown'

export interface Element {
  symbol: string
  name: string
  atomicNumber: number
  atomicMass: number
  /** Angstroms. Sets sphere size in the space-filling model, so it is geometry. */
  vdwRadius: number
  /** Angstroms. Used to estimate bond length where no override is given. */
  covalentRadius: number
  colour: string
  colourBasis: ColourBasis
  /** True macroscopic appearance at STP, shown verbatim in the UI. */
  appearance: string
  material: Material
  /** Rendered semi-transparent: an honest cue that the substance is colourless. */
  translucent: boolean
  phase: ElementPhase
  category: Category
  electronegativity: number | null
}

