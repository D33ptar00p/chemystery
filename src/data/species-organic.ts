/**
 * Organic species data for CheMystery.
 *
 * SOURCE CONVENTION FOR BOND LENGTHS
 * -----------------------------------
 * Every bond in this file carries an explicit `bondLengthOverrides` entry —
 * nothing is left to a generic covalent-radii default — so the numbers here
 * are exactly what renders. Baseline values follow the brief's standard set
 * (CRC Handbook / classic gas-phase spectroscopic and electron-diffraction
 * values, consistent with the sibling inorganic table):
 *   C-H 1.09, C-C 1.54, C=C 1.34, C≡C 1.20, C-O 1.43 (ether/alcohol),
 *   C=O 1.21 (aldehyde/ketone), O-H 0.97, C-N 1.47 (amine), C≡N 1.16,
 *   C-Cl 1.77, C-F 1.35, C-Br 1.94.
 * N-H (1.01 Å) and C-S (1.82 Å) / S-H (1.34 Å) are not in that list but are
 * needed here; both are standard literature values (e.g. methylamine N-H
 * ~1.02-1.03 Å; H2S/thiol S-H ~1.33-1.34 Å).
 *
 * Where a specific, well-characterised structure differs *materially* from
 * the generic table above, the molecule-specific literature value is used
 * instead, and is called out below. Sources are gas-phase electron
 * diffraction (ED) or microwave (MW) spectroscopy unless noted, as these
 * describe isolated molecules — the right comparison for a space-filling
 * model of one molecule, rather than a solid-state/crystal value distorted
 * by packing and hydrogen bonding:
 *   - Aromatic rings (benzene, toluene, phenol, aniline): every ring C-C is
 *     set to the real delocalised 1.39 Å, NOT the alternating 1.34/1.54 a
 *     naive Kekule structure would suggest. The bond *orders* in this file
 *     still alternate 2/1/2/1/2/1 around each ring — that is a drawing
 *     convention only (needed so each ring carbon's steric number/valence
 *     works out), the physical ring is a single delocalised pi system with
 *     six equivalent bonds and 120° angles.
 *   - Conjugated/allylic C-C single bonds are shorter than a plain alkane
 *     C-C: 1,3-butadiene's central C2-C3 bond is 1.46 Å (not 1.54), and
 *     propene's allylic C2-C3 (sp2-sp3) bond is 1.50 Å.
 *   - Any Csp3-C(=O) bond (acetaldehyde, acetone, carboxylic acids, esters,
 *     acyl chloride, anhydride) is likewise shortened to ~1.50-1.52 Å
 *     relative to a plain alkane C-C (e.g. acetone C-C = 1.507 Å, ED).
 *   - Carboxylic acid C=O is 1.23 Å and the C-OH bond is shortened to
 *     ~1.36 Å (conjugation with the carbonyl), vs. 1.43 Å for a plain
 *     alcohol/ether C-O.
 *   - Ester group (ethyl acetate, gas ED, Skancke et al. 1991): C=O
 *     1.20 Å, acyl C-O(bridge) 1.35 Å, bridge O-C(alkyl) 1.45 Å — the two
 *     C-O bonds either side of an ester oxygen are NOT equal.
 *   - Acetic anhydride (gas ED): C=O 1.19 Å, C-O(bridge) 1.40 Å, Csp3-C(=O)
 *     1.50 Å.
 *   - Acetyl chloride: C=O 1.19 Å, C-Cl 1.80 Å (longer than the generic
 *     alkyl C-Cl 1.77 Å — recalled from standard acyl-halide structural
 *     tables; flagged as slightly lower confidence than the ED/MW values
 *     above).
 *   - Nitromethane (ED/MW): C-N 1.49 Å, both N-O bonds 1.22 Å (they are
 *     equivalent by resonance/rotation-averaging; the file draws one as
 *     N=O and one as N-O, a Kekule-style convention exactly like benzene —
 *     both get the same real length).
 *   - Urea (neutron diffraction, Swaminathan/Craven/McMullan 1984): C=O
 *     1.26 Å, C-N 1.35 Å — both are shifted from generic amide/ketone
 *     values by strong resonance donation from both nitrogen lone pairs
 *     into the carbonyl.
 *   - Aniline ring-N bond (MW, Lister et al.): 1.402 Å — shorter than the
 *     generic alkyl C-N (1.47 Å) from conjugation with the ring.
 *   - Phenol ring-O bond: 1.36 Å — shorter than the generic alkyl C-O
 *     (1.43 Å), same conjugation effect.
 *   - Toluene ring-CH3 bond: 1.51 Å (classic gas ED value, Csp2-Csp3).
 *   - CF4 C-F: 1.32 Å — this is NOT the same as a mono-fluorinated C-F
 *     (~1.38 Å in CH3F); C-F bonds shorten measurably as more fluorines
 *     are added to the same carbon (well-documented substituent effect),
 *     so CF4 gets its own, shorter, override rather than the generic
 *     1.35 Å figure.
 *   - CS2: C=S 1.55 Å (rotational spectroscopy; commonly cited as
 *     1.5526 Å).
 *
 * CAVEAT — chain conformation: this schema has no dihedral/torsion field.
 * Longer floppy chains (octane, glycerol, propan-1-ol, the glucose C1-C6
 * backbone) have every LOCAL bond angle fixed by lonePairs + steric number,
 * but nothing here constrains the torsion angle about each C-C single bond.
 * Whether the generator lays these out as a tidy zig-zag or lets them curl
 * up is entirely a property of the geometry-generator, not of this data.
 *
 * CAVEAT — amide-type nitrogen (urea): real urea nitrogens are close to
 * planar (sp2-like) because both N lone pairs conjugate into the C=O. This
 * file still gives urea's N atoms 1 lone pair each (the standard
 * bookkeeping count), which a naive steric-number walker will render
 * pyramidal. Flagged as a known simplification, not an error in the lone
 * pair count itself.
 *
 * GLUCOSE: modelled as the open-chain aldose (as suggested in the brief) to
 * avoid ring-closure entirely. Real glucose is >99% the cyclic pyranose
 * hemiacetal in solution and in the solid; the open-chain form is a minor
 * tautomer used here only because it keeps the bond graph a simple acyclic
 * chain.
 *
 * DROPPED: Sucrose (C12H22O11) is NOT included. Unlike glucose it has no
 * usable open-chain simplification — it is a non-reducing disaccharide
 * whose glycosidic bond locks BOTH rings closed (a pyranose and a
 * furanose), so representing it honestly needs two independent ring
 * closures plus a bridging acetal oxygen across ~45 atoms. That is exactly
 * the failure mode the ring-closure caveat in the brief warns about, and
 * doubling it (two rings, one being a strained 5-membered furanose) is not
 * something this data format or a bond-angle-only VSEPR walker (no real
 * chair/envelope pucker solver) can be expected to close cleanly and
 * reproducibly. See the accompanying reply for the full reasoning.
 *
 * PHASES are at 298 K, 1 bar, decided from each compound's real melting/
 * boiling point (not assumed) — several "liquids" you might expect (e.g.
 * acetaldehyde bp 20.2 °C, methylamine bp -6.3 °C, ethylamine bp 16.6 °C,
 * bromomethane bp 3.6 °C, methanethiol bp 6.0 °C) are actually gases at
 * 298 K and are marked as such.
 */

